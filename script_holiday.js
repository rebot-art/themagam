/* =====================================================================
   script_holiday.js — 🎑 명절 연휴 (2026-09-13, 콩)

   [무엇인가]
   "이번 달은 추석이 있으니 의무 출석일을 좀 낮춰 주자" 는 이야기입니다.
   연휴 날짜를 여기 한 곳에 적어 두면, 멤버 화면(🗂️ 나의 작업)과
   관리자 출근부가 **같은 표를 보고** 기준을 낮춥니다.

   [왜 서버가 아니라 코드인가]
   명절 날짜는 몇 년 치를 미리 알 수 있고, 한 해에 두 번 바뀝니다.
   이런 건 서버에 둘 이유가 없어요 — 서버에 두면 모두의 브라우저가
   매번 읽어 가서 통신량만 늡니다. 여기 적어 두면 통신량 0 입니다.

   [기준이 얼마나 내려가나 — 비율로 (콩 결정 2026-09-13)]
   연휴를 **없는 날**로 치고, 남은 날에 같은 비율을 매깁니다.
     30일 달 · 연휴 4일 → (30−4) ÷ 30 × 18 = 15.6 → **16일**
   🏖️ 휴가가 이미 이렇게 돌고 있어서, 셈법이 두 갈래로 갈리지 않아요.
   (18−4=14 로 하면 남은 26일 중 14일 = 54% 라, 평범한 달의 60% 보다
    기준이 헐거워집니다. 그래서 비율 쪽을 골랐습니다.)

   ★ 연휴에 나오는 건 물론 출석으로 셉니다 — 기준만 내려가요.
   ★ 휴가·개인사정과 겹쳐도 **한 번만** 빠집니다 (두 번 빼면 기준이
     실제보다 더 내려가요 — 부르는 쪽에서 걸러 넣습니다).

   [새 명절을 넣을 때]
   아래 표에 한 줄 더하면 끝입니다. from·to 는 **연휴 첫날과 끝날**이고
   양 끝을 포함해요. 주말이 붙어 쉬는 날이면 그것까지 적습니다 —
   더마감은 주말에도 쓰는 방이라, 달력의 빨간 날이 아니라 **실제로
   못 나오는 날**이 기준이니까요.
   ===================================================================== */
(function () {
  "use strict";

  /* 연휴 표 — from·to 양 끝을 포함합니다.
     2026 추석: 9/24(목)~9/26(토) 공휴일 + 9/27(일) → 실질 나흘.
                (2026년은 토요일이 겹쳐도 대체공휴일이 안 생겨서
                 9/28 월요일은 평범한 평일입니다)
     2027 설날: 2/6(토)~2/8(월) + 2/9(화) 대체공휴일 → 나흘.
     2027 추석: 9/14(화)~9/16(목) → 사흘. */
  const HOLIDAYS = [
    { name: "추석", from: "2026-09-24", to: "2026-09-27" },
    { name: "설날", from: "2027-02-06", to: "2027-02-09" },
    { name: "추석", from: "2027-09-14", to: "2027-09-16" }
    /* ↑ 해마다 한 줄씩 — 콩에게 물어보고 넣습니다 */
  ];

  const 두자리 = (n) => String(n).padStart(2, "0");

  /** 그 달(y, m=0~11)에 드는 연휴 날짜들 — ["2026-09-24", …] */
  function 명절날들(y, m) {
    const 달 = `${y}-${두자리(m + 1)}`;
    const 끝 = new Date(y, m + 1, 0).getDate();
    const out = [];
    for (let d = 1; d <= 끝; d++) {
      const dk = `${달}-${두자리(d)}`;
      if (HOLIDAYS.some(h => dk >= h.from && dk <= h.to)) out.push(dk);
    }
    return out;
  }

  /** 그 달에 든 연휴 이름 — "추석" / "설날·추석" / "" */
  function 명절이름(y, m) {
    const 달 = `${y}-${두자리(m + 1)}`;
    const 이름 = HOLIDAYS
      .filter(h => h.from.slice(0, 7) === 달 || h.to.slice(0, 7) === 달)
      .map(h => h.name);
    return [...new Set(이름)].join("·");
  }

  window.HOLIDAYS       = HOLIDAYS;
  window.holidayDays    = 명절날들;
  window.holidayName    = 명절이름;
})();
